"""Generate docs/periodic-table.md from chemhelper.elements.

    python tools/make_periodic_table.py
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from chemhelper import elements  # noqa: E402


def position(z):
    """(row, column, block) of element z in the 18-column layout."""
    if z == 1:
        return 1, 1, "s"
    if z == 2:
        return 1, 18, "s"
    if z <= 10:
        return (2, z - 2, "s") if z <= 4 else (2, z + 8, "p")
    if z <= 18:
        return (3, z - 10, "s") if z <= 12 else (3, z, "p")
    if z <= 54:
        row, group = (4, z - 18) if z <= 36 else (5, z - 36)
        return row, group, "s" if group <= 2 else "d" if group <= 12 else "p"
    if z <= 56:
        return 6, z - 54, "s"
    if z <= 71:
        return 9, z - 54, "f"
    if z <= 86:
        return 6, z - 68, "d" if z <= 80 else "p"
    if z <= 88:
        return 7, z - 86, "s"
    return 10, z - 86, "f"


def main():
    cells = []
    for e in elements.element_objects:
        row, col, block = position(e.atomic_number)
        cells.append(
            '<div class="pt-cell pt-{b}" style="grid-row:{r};grid-column:{c}" '
            'title="{name} (Z = {z}), {mass} g/mol">'
            '<span class="pt-z">{z}</span><span class="pt-sym">{sym}</span>'
            '<span class="pt-name">{name}</span><span class="pt-mass">{mass}</span></div>'.format(
                b=block, r=row, c=col, name=e.name, z=e.atomic_number, sym=e.symbol, mass=e.mass)
        )
    rows = ["| {} | `{}` | {} | {} |".format(e.atomic_number, e.symbol, e.name, e.mass)
            for e in elements.element_objects]
    page = TEMPLATE.format(cells="\n".join(cells), rows="\n".join(rows))
    (ROOT / "docs" / "periodic-table.md").write_text(page, encoding="utf-8", newline="\n")
    print("Wrote docs/periodic-table.md")


